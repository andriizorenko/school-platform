  event_type TEXT NOT NULL REFERENCES notification_event_types(code) ON DELETE CASCADE,
  role_code TEXT NOT NULL REFERENCES roles(code) ON DELETE CASCADE,
  PRIMARY KEY (event_type, role_code)
);

CREATE INDEX IF NOT EXISTS notification_event_roles_role_idx
  ON notification_event_roles(role_code, event_type);

